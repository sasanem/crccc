namespace RegexSearch.Core.Models
{
    /// <summary>
    /// Состояния конечного автомата для распознавания ИНН организации (10 цифр).
    /// </summary>
    public enum State
    {
        Start,  // q0 — начальное состояние, просмотр текста
        D1, D2, D3, D4, D5, D6, D7, D8, D9, // q1..q9 — прочитано 1..9 цифр подряд
        Done,   // q10 — принимающее состояние: прочитано ровно 10 цифр
        Error   // попытка распознавания прервана (встретился не-цифровой символ)
    }
}
